#include <stdio.h>
#define NMAX 10

int input(int *a, int *n);
void output(int *a, int n);
void squaring(int *a, int n);

int main()
{
    int n, data[NMAX];
    
    // Вызываем функцию ввода и проверяем, вернула ли она ошибку
    // Если input вернул не 0 (то есть была ошибка ввода) - выводим "n/a"
    if (input(data, &n) != 0) {
        printf("n/a");
        return 0;  // Завершаем программу
    }
    
    squaring(data, n);
    output(data, n);

    return 0;
}

int input(int *a, int *n)
{
    // Читаем количество элементов и проверяем 3 вещи:
    // 1) scanf вернул 1 (успешно прочитали число)
    // 2) n больше 0 (массив не пустой)
    // 3) n не больше 10 (не превышает размер массива)
    // Если хоть что-то не так - возвращаем 1 (ошибка)
    if (scanf("%d", n) != 1 || *n <= 0 || *n > NMAX) {
        return 1;
    }
    
    // Проходим по массиву указателем p
    for(int *p = a; p - a < *n; p++)
    {
        // Читаем каждое число и проверяем, успешно ли прочитали
        // Если scanf вернул не 1 - была ошибка, возвращаем 1
        if (scanf("%d", p) != 1) {
            return 1;
        }
    }
    
    // Если всё хорошо - возвращаем 0 (успех)
    return 0;
}

void output(int *a, int n)
{
    // Проходим по массиву указателем p от начала до конца
    for (int *p = a; p - a < n; p++) {
        // Выводим число, на которое указывает p
        printf("%d", *p);
        // Если это не последний элемент - добавляем пробел после числа
        if (p - a < n - 1) {
            printf(" ");
        }
    }
}

void squaring(int *a, int n)
{
    // Проходим по массиву указателем p от начала до конца
    for (int *p = a; p - a < n; p++) {
        // Умножаем число само на себя (возводим в квадрат)
        // *p - это значение, на которое указывает p
        *p = (*p) * (*p);
    }
}
