#include <stdio.h>
#define NMAX 10  // максимум элементов (чтобы не выйти за пределы массива)

int input(int *a, int *n);
void output(int *a, int n);
void squaring(int *a, int n);

int main() {
    int n = 0;          // сюда запишем, сколько чисел ввёл пользователь
    int data[NMAX];     // здесь храним сами числа (не больше 10 штук)

    // Пытаемся прочитать ввод. Если что-то пошло не так — пишем "n/a" и выходим.
    if (input(data, &n) != 0) {
        printf("n/a");
        return 0;
    }

    // Если ввод успешный — возводим каждое число в квадрат
    squaring(data, n);

    // И печатаем результат
    output(data, n);

    return 0;
}

int input(int *a, int *n) {
    // Сначала читаем, сколько чисел нам собираются дать.
    // Проверяем сразу три вещи:
    // 1) scanf вернул 1 (значит реально прочитал число);
    // 2) число > 0 (должен быть хотя бы один элемент);
    // 3) число <= NMAX (не больше максимума, чтобы не сломать массив).
    if (scanf("%d", n) != 1 || *n <= 0 || *n > NMAX) {
        return 1;  // если что-то из этого не так — сообщаем об ошибке
    }

    // Теперь читаем сами числа по одному.
    for (int i = 0; i < *n; i++) {
        // Если ввели не число — тоже ошибка.
        if (scanf("%d", &a[i]) != 1) {
            return 1;
        }
    }

    return 0;  // всё прошло хорошо
}

void squaring(int *a, int n) {
    // Идём по каждому числу и умножаем его само на себя (квадрат).
    for (int i = 0; i < n; i++) {
        a[i] = a[i] * a[i];
    }
}

void output(int *a, int n) {
    // Печатаем все числа подряд через пробел.
    for (int i = 0; i < n; i++) {
        printf("%d", a[i]);
        if (i < n - 1) {
            printf(" ");  // пробел между числами, но не после последнего
        }
    }
}
