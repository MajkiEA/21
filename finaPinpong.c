// === НАЧАЛО: Функция вывода счёта большими цифрами, центр по сетке ===
void PrintScore(int ScreenX, int GoalLeft, int GoalRight) {
    printf("\n");  // Отступ сверху

    /*
     * Цель: чтобы двоеточие стояло в той же колонке, где в поле рисуется сетка (x == width/2).
     * Ширина одной большой цифры = 5 символов.
     * Разделитель "  :  " = 5 символов, сама ':' — в позиции 2 (0‑индекс) внутри разделителя.
     * Колонка двоеточия = offset + 5 (левая цифра) + 2 = offset + 7.
     * Хотим: offset + 7 == ScreenX/2  → offset = ScreenX/2 - 7.
     */
    int offset = ScreenX / 2 - 7;

    // Выводим 5 строк больших цифр
    for (int line = 0; line < 5; line++) {
        printf("%*s", offset, " ");  // Центрируем так, чтобы ':' совпало с центральной полосой

        // Левая цифра (синий)
        printf("\x1b[34m");  // Синий цвет
        PrintBigDigit(GoalLeft, line);
        printf("\x1b[0m");   // Сброс цвета

        // Разделитель ':', центрирован относительно сетки
        if (line == 2) {
            printf("  :  ");
        } else {
            printf("     ");
        }

        // Правая цифра (красный)
        printf("\x1b[31m");  // Красный цвет
        PrintBigDigit(GoalRight, line);
        printf("\x1b[0m");   // Сброс цвета

        printf("\n");
    }

    printf("\n");  // Отступ снизу
}
