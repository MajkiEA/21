/*------------------------------------
    Программа циклического сдвига массива
    
    Что это:
    "Циклический сдвиг" - элементы массива
    двигаются влево или вправо, а те что "выпадают"
    с одного конца, появляются с другого
    
    Примеры:
    Сдвиг влево на 2: [1,2,3,4,5] → [3,4,5,1,2]
    Сдвиг вправо на 2: [1,2,3,4,5] → [4,5,1,2,3]
-------------------------------------*/

#include <stdio.h>

#define MAX_SIZE 10

// Объявляем все функции программы
int input(int *buffer, int *length, int *shift);
void output(const int *buffer, int length);
void cycle_shift(int *buffer, int length, int shift);
void reverse(int *buffer, int start, int end);

/*------------------------------------
    Главная функция программы
    
    Что делает: 
    1. Считывает длину массива, сам массив и величину сдвига
    2. Проверяет корректность данных
    3. Выполняет циклический сдвиг
    4. Выводит результат
-------------------------------------*/
int main(void)
{
    int length = 0;           // Длина массива
    int shift = 0;            // Величина сдвига
    int buffer[MAX_SIZE];     // Массив данных
    int error = 0;            // Флаг ошибки:  0 - OK, 1 - ошибка
    
    // Шаг 1: Считываем все данные
    error = input(buffer, &length, &shift);
    
    // Шаг 2: Проверяем корректность длины массива
    if (error == 0) {
        if (length <= 0 || length > MAX_SIZE) {
            error = 1;
        }
    }
    
    // Шаг 3: Если данные корректны - выполняем сдвиг и выводим
    if (error == 0) {
        cycle_shift(buffer, length, shift);
        output(buffer, length);
    } else {
        printf("n/a");
    }
    
    return 0;
}

/*------------------------------------
    Функция ввода всех данных
    
    Что считывает:
    1. Длину массива (n)
    2. Элементы массива (n чисел)
    3. Величину сдвига (c)
    
    Пример ввода: 
    5
    1 2 3 4 5
    2
    
    Возвращает:
    0 - если всё прочиталось успешно
    1 - если была ошибка чтения
-------------------------------------*/
int input(int *buffer, int *length, int *shift)
{
    int error = 0;
    
    // Читаем длину массива
    if (scanf("%d", length) != 1) {
        error = 1;
    }
    
    // Если длина прочиталась, читаем элементы массива
    if (error == 0) {
        int i = 0;
        while (i < *length && error == 0) {
            if (scanf("%d", &buffer[i]) != 1) {
                error = 1;
            }
            i++;
        }
    }
    
    // Если элементы прочитались, читаем величину сдвига
    if (error == 0) {
        if (scanf("%d", shift) != 1) {
            error = 1;
        }
    }
    
    return error;
}

/*------------------------------------
    Функция вывода массива
    
    Выводит все элементы через пробел
    
    Пример: 
    buffer = [1, 2, 3] → выведет "1 2 3"
-------------------------------------*/
void output(const int *buffer, int length)
{
    int i = 0;
    while (i < length) {
        printf("%d", buffer[i]);
        if (i < length - 1) {
            printf(" ");
        }
        i++;
    }
}

/*------------------------------------
    Функция циклического сдвига массива
    
    Как работает:
    - Положительный shift → сдвиг ВЛЕВО
      [1,2,3,4,5] сдвиг 2 → [3,4,5,1,2]
      
    - Отрицательный shift → сдвиг ВПРАВО
      [1,2,3,4,5] сдвиг -2 → [4,5,1,2,3]
    
    Алгоритм "тройного разворота": 
    Чтобы сдвинуть [1,2,3,4,5] влево на 2:
    1. Развернуть первые 2: [2,1,3,4,5]
    2. Развернуть остальные: [2,1,5,4,3]
    3. Развернуть всё: [3,4,5,1,2] ✓
-------------------------------------*/
void cycle_shift(int *buffer, int length, int shift)
{
    // Если массив пустой - ничего не делаем
    if (length > 0) {
        // Объявляем переменную здесь, где она используется
        int normalized_shift;
        
        // Нормализуем сдвиг к диапазону [0, length)
        // Пример: сдвиг 12 при длине 10 = сдвиг 2
        normalized_shift = shift % length;
        
        // Если сдвиг отрицательный, преобразуем в положительный
        // Сдвиг вправо на 2 = сдвиг влево на (length - 2)
        if (normalized_shift < 0) {
            normalized_shift = length + normalized_shift;
        }
        
        // Выполняем "магию тройного разворота"
        reverse(buffer, 0, normalized_shift - 1);
        reverse(buffer, normalized_shift, length - 1);
        reverse(buffer, 0, length - 1);
    }
}

/*------------------------------------
    Вспомогательная функция разворота
    части массива
    
    Что делает:
    Переворачивает элементы от позиции start
    до позиции end (включительно)
    
    Пример:
    [1, 2, 3, 4, 5], start=1, end=3
    Результат: [1, 4, 3, 2, 5]
    (развернули 2-й, 3-й, 4-й элементы)
-------------------------------------*/
void reverse(int *buffer, int start, int end)
{
    // Идём с двух концов к центру и меняем местами
    while (start < end) {
        int temp = buffer[start];
        buffer[start] = buffer[end];
        buffer[end] = temp;
        start++;
        end--;
    }
}
