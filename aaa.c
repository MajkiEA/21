
/*------------------------------------
    Программа циклического сдвига массива
    
    Что это значит:
    "Циклический сдвиг" - это когда элементы массива
    двигаются влево или вправо, а те, что "выпадают"
    с одного конца, появляются с другого конца
    
    Пример сдвига влево на 2:
    [1, 2, 3, 4, 5] → [3, 4, 5, 1, 2]
    
    Пример сдвига вправо на 2:
    [1, 2, 3, 4, 5] → [4, 5, 1, 2, 3]
-------------------------------------*/

#include <stdio. h>

// Объявляем все функции
int input(int *buffer, int *length, int *shift);
void output(const int *buffer, int length);
void cycle_shift(int *buffer, int length, int shift);
void reverse(int *buffer, int start, int end);

/*------------------------------------
    Главная функция программы
-------------------------------------*/
int main()
{
    int length;       // Сколько чисел в массиве
    int shift;        // На сколько позиций сдвигать
    int buffer[10];   // Сам массив (максимум 10 чисел)
    int error = 0;    // Флаг ошибки
    
    // Шаг 1: Считываем данные
    error = input(buffer, &length, &shift);
    
    // Шаг 2: Проверяем корректность длины массива
    if (error == 0) {
        if (length <= 0 || length > 10) {
            error = 1;  // Длина неправильная
        }
    }
    
    // Шаг 3: Если всё хорошо - делаем сдвиг и выводим результат
    if (error == 0) {
        cycle_shift(buffer, length, shift);
        output(buffer, length);
    } else {
        printf("n/a");  // Если ошибка - выводим "n/a"
    }
    
    return 0;  // Единственный выход из функции
}

/*------------------------------------
    Функция ввода данных
    
    Что делает: 
    1. Читает длину массива
    2. Читает элементы массива
    3. Читает величину сдвига
    
    Возвращает:
    0 - если всё хорошо
    1 - если была ошибка при чтении
-------------------------------------*/
int input(int *buffer, int *length, int *shift)
{
    int error = 0;  // Флаг ошибки
    
    // Читаем длину массива
    if (scanf("%d", length) != 1) {
        error = 1;  // Не удалось прочитать
    }
    
    // Если длина прочиталась, читаем элементы
    if (error == 0) {
        for (int i = 0; i < *length; i++) {
            if (scanf("%d", &buffer[i]) != 1) {
                error = 1;  // Не удалось прочитать элемент
            }
        }
    }
    
    // Если элементы прочитались, читаем сдвиг
    if (error == 0) {
        if (scanf("%d", shift) != 1) {
            error = 1;  // Не удалось прочитать сдвиг
        }
    }
    
    return error;  // Возвращаем результат (0 - OK, 1 - ошибка)
}

/*------------------------------------
    Функция вывода массива
    
    Выводит все числа через пробел
-------------------------------------*/
void output(const int *buffer, int length)
{
    for (int i = 0; i < length; i++) {
        printf("%d", buffer[i]);
        if (i < length - 1) {
            printf(" ");
        }
    }
}

/*------------------------------------
    Функция циклического сдвига
    
    Как работает:
    - Положительный shift → сдвиг влево
      Пример: [1,2,3,4,5] сдвиг на 2 → [3,4,5,1,2]
      
    - Отрицательный shift → сдвиг вправо
      Пример: [1,2,3,4,5] сдвиг на -2 → [4,5,1,2,3]
    
    Используем "трюк с тройным разворотом":
    Чтобы сдвинуть [1,2,3,4,5] влево на 2:
    1. Развернем первые 2: [2,1,3,4,5]
    2. Развернем остальные: [2,1,5,4,3]
    3. Развернем весь массив: [3,4,5,1,2] ✓
-------------------------------------*/
void cycle_shift(int *buffer, int length, int shift)
{
    // Если массив пустой - ничего не делаем
    if (length <= 0) {
        return;
    }
    
    // Приводим сдвиг к диапазону [0, length)
    // Например:  сдвиг на 12 при длине 10 = сдвиг на 2
    shift = shift % length;
    
    // Если сдвиг отрицательный (вправо), делаем его положительным
    // Сдвиг вправо на 2 = сдвиг влево на (length - 2)
    if (shift < 0) {
        shift = length + shift;
    }
    
    // Магия тройного разворота: 
    reverse(buffer, 0, shift - 1);        // Развернули начало
    reverse(buffer, shift, length - 1);   // Развернули конец
    reverse(buffer, 0, length - 1);       // Развернули всё
}

/*------------------------------------
    Вспомогательная функция разворота части массива
    
    Что делает:
    Переворачивает элементы от позиции start до end
    
    Пример:
    [1, 2, 3, 4, 5], start=1, end=3
    Результат: [1, 4, 3, 2, 5]
    (развернули элементы со 2-го по 4-й)
-------------------------------------*/
void reverse(int *buffer, int start, int end)
{
    // Идем с двух концов к центру
    while (start < end) {
        // Меняем местами элементы
        int temp = buffer[start];       // Запоминаем первый
        buffer[start] = buffer[end];    // Копируем последний на место первого
        buffer[end] = temp;             // Копируем первый на место последнего
        
        // Двигаемся к центру
        start++;
        end--;
    }
}
