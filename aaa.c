#include <stdio.h>

#define MAX_SIZE 10

// Объявляем все функции программы
void input(int *buffer, int *length);
void output(const int *buffer, int length);
int sum_numbers(const int *buffer, int length);
int find_numbers(const int *buffer, int length, int number, int *numbers);

/*------------------------------------
	Главная функция программы
	
	Что делает: 
	1. Считывает массив чисел
	2. Находит сумму всех ЧЕТНЫХ чисел (0 - нечетное)
	3. Находит все элементы, на которые эта сумма делится
	4. Выводит сумму и массив делителей
	
	Если четных нет или делителей нет → выводит "n/a"
-------------------------------------*/
int main(void)
{
    int length = 0;          // Длина массива
    int buffer[MAX_SIZE];    // Исходный массив
    int numbers[MAX_SIZE];   // Массив делителей
    int sum = 0;             // Сумма четных элементов
    int count = 0;           // Количество делителей
    int error = 0;           // Флаг ошибки
    
    // Шаг 1: Считываем данные
    input(buffer, &length);
    
    // Шаг 2: Считаем сумму четных элементов
    sum = sum_numbers(buffer, length);
    
    // Шаг 3: Проверяем, что сумма не ноль (есть четные числа)
    if (sum == 0) {
        error = 1;
    }
    
    // Шаг 4: Если сумма есть, ищем делители
    if (error == 0) {
        count = find_numbers(buffer, length, sum, numbers);
        if (count == 0) {
            error = 1;
        }
    }
    
    // Шаг 5: Выводим результат
    if (error == 0) {
        printf("%d\n", sum);
        output(numbers, count);
    } else {
        printf("n/a");
    }
    
    return 0;
}

/*------------------------------------
	Функция ввода данных
	
	Что делает:
	Читает сначала длину массива,
	потом сами числа через пробел
	
	Пример:
	Вход: 5
	      1 2 3 4 5
	Результат: buffer=[1,2,3,4,5], length=5
-------------------------------------*/
void input(int *buffer, int *length)
{
    scanf("%d", length);
    
    int i = 0;
    while (i < *length) {
        scanf("%d", &buffer[i]);
        i++;
    }
}

/*------------------------------------
	Функция вывода массива
	
	Выводит все числа через пробел
	
	Пример:  [1, 2, 3] → "1 2 3"
-------------------------------------*/
void output(const int *buffer, int length)
{
    int i = 0;
    while (i < length) {
        printf("%d", buffer[i]);
        if (i < length - 1) {
            printf(" ");
        }
        i++;
    }
}

/*------------------------------------
	Функция подсчета суммы четных чисел
	
	Что делает:
	Проходит по массиву и суммирует ЧЕТНЫЕ числа
	(0 считается НЕЧЕТНЫМ по условию)
	
	Пример:
	[4, 3, 9, 0, 1, 2, 0, 2, 7, -1]
	Четные: 4, 2, 2
	Сумма: 4 + 2 + 2 = 8
-------------------------------------*/
int sum_numbers(const int *buffer, int length)
{
    int sum = 0;
    int i = 0;
    
    while (i < length) {
        // Проверяем: 
        // 1. Число не ноль (0 - нечетное)
        // 2. Число делится на 2 без остатка (четное)
        if (buffer[i] != 0 && buffer[i] % 2 == 0) {
            sum = sum + buffer[i];
        }
        i++;
    }
    
    return sum;
}

/*------------------------------------
	Функция поиска делителей
	
	Что делает:
	Находит все элементы массива, на которые
	заданное число делится нацело
	
	Пример:
	Массив:  [4, 1, 2, 2, -1]
	Число: 8
	Делители: 4 (8/4=2), 1 (8/1=8), 2, 2, -1
	
	Возвращает:  количество найденных делителей
-------------------------------------*/
int find_numbers(const int *buffer, int length, int number, int *numbers)
{
    int count = 0;
    int i = 0;
    
    while (i < length) {
        // Проверяем:
        // 1. Элемент не ноль (на 0 делить нельзя)
        // 2. Число делится на этот элемент нацело
        if (buffer[i] != 0 && number % buffer[i] == 0) {
            numbers[count] = buffer[i];
            count++;
        }
        i++;
    }
    
    return count;
}
