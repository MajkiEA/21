/*------------------------------------
    Программа циклического сдвига
    массива влево/вправо
-------------------------------------*/

#include <stdio.h>

// Объявляем функции, которые будем использовать
void input(int *buffer, int *length, int *shift);
void output(const int *buffer, int length);
void cycle_shift(int *buffer, int length, int shift);
void reverse(int *buffer, int start, int end);

/*------------------------------------
    Основная функция программы
-------------------------------------*/
int main()
{
    int length;       // Длина массива
    int shift;        // На сколько позиций сдвигать
    int buffer[10];   // Сам массив (максимум 10 элементов)
    
    // Считываем данные от пользователя
    input(buffer, &length, &shift);
    
    // Проверяем, что длина корректная (от 1 до 10)
    if (length <= 0 || length > 10) {
        printf("n/a");  // Если нет - выводим ошибку
        return 0;
    }
    
    // Делаем циклический сдвиг массива
    cycle_shift(buffer, length, shift);
    
    // Выводим результат на экран
    output(buffer, length);
    
    return 0;
}

/*------------------------------------
    Функция ввода данных: 
    длина массива, элементы массива,
    величина сдвига
-------------------------------------*/
void input(int *buffer, int *length, int *shift)
{
    // Читаем длину массива
    if (scanf("%d", length) != 1) {
        *length = -1;  // Если не удалось - ставим ошибку
        return;
    }
    
    // Читаем элементы массива по одному
    for (int i = 0; i < *length; i++) {
        if (scanf("%d", &buffer[i]) != 1) {
            *length = -1;  // Если не удалось - ставим ошибку
            return;
        }
    }
    
    // Читаем величину сдвига
    if (scanf("%d", shift) != 1) {
        *length = -1;  // Если не удалось - ставим ошибку
    }
}

/*------------------------------------
    Функция вывода массива
-------------------------------------*/
void output(const int *buffer, int length)
{
    // Выводим все элементы массива через пробел
    for (int i = 0; i < length; i++) {
        printf("%d", buffer[i]);
        
        // После каждого элемента ставим пробел, кроме последнего
        if (i < length - 1) {
            printf(" ");
        }
    }
}

/*------------------------------------
    Функция циклического сдвига массива
    Положительный shift - сдвиг влево
    Отрицательный shift - сдвиг вправо
    
    Пример сдвига влево на 2: 
    [1,2,3,4,5] -> [3,4,5,1,2]
    
    Пример сдвига вправо на 2 (shift = -2):
    [1,2,3,4,5] -> [4,5,1,2,3]
-------------------------------------*/
void cycle_shift(int *buffer, int length, int shift)
{
    // Если массив пустой - ничего не делаем
    if (length <= 0) {
        return;
    }
    
    // Приводим сдвиг к нормальному диапазону
    // Например, сдвиг на 12 при длине 10 = сдвиг на 2
    shift = shift % length;
    
    // Если сдвиг отрицательный (сдвиг вправо),
    // превращаем его в эквивалентный сдвиг влево
    // Например:  сдвиг вправо на 2 = сдвиг влево на (length - 2)
    if (shift < 0) {
        shift = length + shift;
    }
    
    // Используем хитрый алгоритм "тройного разворота": 
    // Чтобы сдвинуть массив [1,2,3,4,5] влево на 2 позиции:
    // 1. Разворачиваем первые 2: [2,1,3,4,5]
    // 2. Разворачиваем остальные: [2,1,5,4,3]
    // 3. Разворачиваем весь массив: [3,4,5,1,2] - готово!
    
    reverse(buffer, 0, shift - 1);        // Шаг 1
    reverse(buffer, shift, length - 1);   // Шаг 2
    reverse(buffer, 0, length - 1);       // Шаг 3
}

/*------------------------------------
    Вспомогательная функция разворота
    части массива от индекса start 
    до индекса end включительно
    
    Пример: reverse([1,2,3,4,5], 1, 3)
    Развернет элементы с индексами 1-3:
    [1,4,3,2,5]
-------------------------------------*/
void reverse(int *buffer, int start, int end)
{
    // Идем с двух концов к центру и меняем элементы местами
    while (start < end) {
        // Запоминаем первый элемент во временную переменную
        int temp = buffer[start];
        
        // Переносим последний элемент на место первого
        buffer[start] = buffer[end];
        
        // Переносим первый элемент (из temp) на место последнего
        buffer[end] = temp;
        
        // Двигаемся к центру
        start++;
        end--;
    }
}
