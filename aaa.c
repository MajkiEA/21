
#include <stdio.h>

#define LEN 100

// Объявляем все функции, которые будем использовать
void sum(int *buff1, int len1, int *buff2, int len2, int *result, int *result_length);
void sub(const int *buff1, int len1, const int *buff2, int len2, int *result, int *result_length);
int input(int *buffer, int *length);
void output(const int *buffer, int length);
int compare(const int *buff1, int len1, const int *buff2, int len2);
int validate_digits(const int *buffer, int length);

/*
    Беззнаковая целочисленная длинная арифметика
    с использованием массивов.  
    
    Что делает программа:
    Складывает и вычитает ОЧЕНЬ большие числа,
    которые не помещаются в обычный int или long long.  
    
    Как работает:
    Числа представлены как массивы цифр.  
    Например:  число 12345 → массив [1, 2, 3, 4, 5]
    
    Ввод:   
     * 2 длинных числа в виде массивов до 100 элементов.   
     * В один элемент массива нельзя вводить число > 9.
     * Например:    1 2 3 означает число 123
     
    Вывод:  
     * Результат сложения (первая строка)
     * Результат вычитания (вторая строка)
     * Если вычитаемое больше уменьшаемого → выводим "n/a"
     
    Пример:   
     * Ввод:  
       1 9 4 4 6 7 4 4 0 7 3 7 0 9 5 5 1 6 1  (огромное число)
       2 9                                     (число 29)

       Вывод:
       1 9 4 4 6 7 4 4 0 7 3 7 0 9 5 5 1 9 0  (сумма)
       1 9 4 4 6 7 4 4 0 7 3 7 0 9 5 5 1 3 2  (разность)
*/
int main()
{
    int buff1[LEN];      // Первое большое число (массив цифр)
    int buff2[LEN];      // Второе большое число (массив цифр)
    int len1 = 0;        // Сколько цифр в первом числе
    int len2 = 0;        // Сколько цифр во втором числе
    int error = 0;       // Флаг ошибки:   0 - всё OK, 1 - есть ошибка
    
    // Шаг 1: Считываем первое число
    error = input(buff1, &len1);
    
    // Шаг 2: Если первое число прочиталось, читаем второе
    if (error == 0) {
        error = input(buff2, &len2);
    }
    
    // Шаг 3: Проверяем, что длины чисел корректные
    // (не пустые и не больше 100 цифр)
    if (error == 0) {
        if (len1 <= 0 || len2 <= 0 || len1 > LEN || len2 > LEN) {
            error = 1;  // Устанавливаем флаг ошибки
        }
    }
    
    // Шаг 4: Проверяем, что все цифры первого числа в диапазоне 0-9
    if (error == 0) {
        error = validate_digits(buff1, len1);
    }
    
    // Шаг 5: Проверяем, что все цифры второго числа в диапазоне 0-9
    if (error == 0) {
        error = validate_digits(buff2, len2);
    }
    
    // Шаг 6: Если есть ошибка - выводим "n/a" и выходим
    if (error != 0) {
        printf("n/a");
    } else {
        // Если всё хорошо - выполняем операции
        
        // Объявляем массив для результата только здесь (когда он нужен)
        int result[LEN + 1];
        int result_len = 0;
        
        // СЛОЖЕНИЕ:   складываем два больших числа
        sum(buff1, len1, buff2, len2, result, &result_len);
        output(result, result_len);  // Выводим результат
        printf("\n");  // Переходим на новую строку
        
        // ВЫЧИТАНИЕ:  вычитаем второе число из первого
        sub(buff1, len1, buff2, len2, result, &result_len);
        
        // Если result_len = -1, значит второе число больше первого
        if (result_len < 0) {
            printf("n/a");  // Нельзя из меньшего вычесть большее
        } else {
            output(result, result_len);  // Выводим результат
        }
    }
    
    return 0;  // Единственный выход из программы
}

/*------------------------------------
    Функция ввода одного большого числа
    
    Что делает:  
    Читает цифры через пробел до конца строки
    и записывает их в массив
    
    Например:  
    Ввод:  "1 2 3"
    Результат: buffer = [1, 2, 3], length = 3
    
    Возвращает: 
    0 - если всё прочиталось успешно
    1 - если была ошибка при чтении
-------------------------------------*/
int input(int *buffer, int *length)
{
    *length = 0;        // Начинаем с нулевой длины
    char c = ' ';       // Символ после числа (пробел или \n)
    int reading = 1;    // Флаг:   продолжаем читать или нет
    
    // Читаем числа, пока не закончится строка или массив
    while (reading != 0 && *length < LEN) {
        // Пытаемся прочитать число и следующий символ
        if (scanf("%d%c", &buffer[*length], &c) != 2) {
            // Не удалось прочитать - ошибка
            reading = 0;
            *length = -1;  // Помечаем как ошибку
        } else {
            // Прочитали успешно
            (*length)++;  // Увеличиваем счетчик цифр
            
            // Если после числа перевод строки - это конец ввода
            if (c == '\n') {
                reading = 0;  // Прекращаем чтение
            }
        }
    }
    
    // Возвращаем код результата
    return (*length <= 0) ? 1 : 0;  // 0 - OK, 1 - ошибка
}

/*------------------------------------
    Функция проверки цифр
    
    Что делает:
    Проверяет, что все элементы массива
    находятся в диапазоне 0-9
    (то есть являются цифрами)
    
    Возвращает:  
    0 - всё OK, все цифры правильные
    1 - есть ошибка, найдена цифра вне диапазона
-------------------------------------*/
int validate_digits(const int *buffer, int length)
{
    int error = 0;  // Флаг ошибки
    int i = 0;      // Счетчик для цикла
    
    // Проверяем каждую цифру, пока не найдем ошибку
    while (i < length && error == 0) {
        // Если цифра меньше 0 или больше 9 - это ошибка
        if (buffer[i] < 0 || buffer[i] > 9) {
            error = 1;  // Нашли неправильную цифру
        }
        i++;
    }
    
    return error;  // Возвращаем результат проверки
}

/*------------------------------------
    Функция вывода большого числа
    
    Что делает:
    Выводит все цифры массива через пробел
    
    Например:
    buffer = [1, 2, 3] → выведет "1 2 3"
-------------------------------------*/
void output(const int *buffer, int length)
{
    // Проходим по всем цифрам
    for (int i = 0; i < length; i++) {
        printf("%d", buffer[i]);  // Выводим цифру
        
        // После каждой цифры ставим пробел (кроме последней)
        if (i < length - 1) {
            printf(" ");
        }
    }
}

/*------------------------------------
    Функция сравнения двух больших чисел
    
    Что делает:
    Определяет, какое число больше
    
    Как работает:
    1. Сначала смотрим на длину (количество цифр)
       Если у одного числа больше цифр - оно больше
       Например: 1000 (4 цифры) > 999 (3 цифры)
       
    2. Если длины равны, сравниваем поцифрово слева направо
       Например:   456 > 123, потому что 4 > 1
    
    Возвращает:
     1  - если buff1 > buff2  (первое больше)
     0  - если buff1 == buff2 (числа равны)
    -1  - если buff1 < buff2  (первое меньше)
-------------------------------------*/
int compare(const int *buff1, int len1, const int *buff2, int len2)
{
    int result = 0;  // Результат сравнения
    
    // Сначала сравниваем количество цифр
    if (len1 > len2) {
        result = 1;   // У первого больше цифр - оно больше
    } else if (len1 < len2) {
        result = -1;  // У второго больше цифр - оно больше
    } else {
        // Количество цифр одинаковое, сравниваем поцифрово
        int i = 0;
        while (i < len1 && result == 0) {
            if (buff1[i] > buff2[i]) {
                result = 1;   // Первая большая цифра
            } else if (buff1[i] < buff2[i]) {
                result = -1;  // Первая меньшая цифра
            }
            i++;
        }
        // Если все цифры одинаковые, result останется 0 (числа равны)
    }
    
    return result;
}

/*------------------------------------
    Функция СЛОЖЕНИЯ двух больших чисел
    
    Как работает:
    Складываем "столбиком" справа налево,
    точно так же, как учили в школе:  
    
    Пример: 
      1 2 3
    +   4 5
    -------
      1 6 8
      
    Процесс: 
    1. Складываем 3 + 5 = 8
    2. Складываем 2 + 4 = 6
    3. Складываем 1 + 0 = 1
    
    Если сумма двух цифр >= 10:
    - Записываем остаток (например, 15 → пишем 5)
    - Запоминаем "перенос" 1 в следующий разряд
      (как говорят "один в уме")
-------------------------------------*/
void sum(int *buff1, int len1, int *buff2, int len2, int *result, int *result_length)
{
    int carry = 0;           // Перенос в следующий разряд ("в уме")
    int i1 = len1 - 1;       // Индекс в первом числе (идем справа)
    int i2 = len2 - 1;       // Индекс во втором числе (идем справа)
    int pos = 0;             // Позиция в результате
    int temp[LEN + 1];       // Временный массив (заполняем задом наперед)
    int continue_loop = 1;   // Флаг продолжения цикла
    
    // Складываем, пока есть цифры или перенос
    while (continue_loop != 0) {
        // Берем цифру из первого числа (или 0, если цифры закончились)
        int digit1 = (i1 >= 0) ? buff1[i1] : 0;
        
        // Берем цифру из второго числа (или 0, если цифры закончились)
        int digit2 = (i2 >= 0) ? buff2[i2] : 0;
        
        // Складываем две цифры + перенос из предыдущего разряда
        int sum_digits = digit1 + digit2 + carry;
        
        // Цифра результата = остаток от деления на 10
        // Например: 7 + 8 + 1 = 16 → цифра = 6
        temp[pos] = sum_digits % 10;
        
        // Новый перенос = целая часть от деления на 10
        // Например: 16 / 10 = 1 (переносим в следующий разряд)
        carry = sum_digits / 10;
        
        pos++;   // Переходим к следующей позиции
        i1--;    // Двигаемся влево по первому числу
        i2--;    // Двигаемся влево по второму числу
        
        // Проверяем, нужно ли продолжать
        // Останавливаемся, когда закончились цифры и нет переноса
        if (i1 < 0 && i2 < 0 && carry == 0) {
            continue_loop = 0;
        }
    }
    
    // ВАЖНО: Убираем ведущие нули из результата! 
    // Например: [0, 0, 1, 1] → [1, 1]
    // Но если все нули, оставляем один:  [0, 0, 0] → [0]
    while (pos > 1 && temp[pos - 1] == 0) {
        pos--;
    }
    
    // Результат у нас получился задом наперед, переворачиваем его
    *result_length = pos;
    for (int i = 0; i < pos; i++) {
        result[i] = temp[pos - 1 - i];
    }
}

/*------------------------------------
    Функция ВЫЧИТАНИЯ двух больших чисел
    
    Что делает:
    Вычитает buff2 ИЗ buff1 (buff1 - buff2)
    
    Как работает:  
    Вычитаем "столбиком" справа налево,
    как учили в школе:  
    
    Пример: 
      1 2 3
    -   4 5
    -------
        7 8
        
    Процесс:  
    1. Вычитаем 3 - 5: не можем!  
       Занимаем 10 → (13 - 5 = 8)
    2. Вычитаем 2 - 4 - 1(заем): не можем!
       Занимаем 10 → (12 - 4 - 1 = 7)
    3. Вычитаем 1 - 0 - 1(заем) = 0
       Ведущий ноль убираем
    
    Важно: 
    Если buff2 > buff1, возвращаем ошибку
    (нельзя из меньшего вычесть большее для положительных чисел)
-------------------------------------*/
void sub(const int *buff1, int len1, const int *buff2, int len2, int *result, int *result_length)
{
    // Проверяем, что первое число >= второго
    if (compare(buff1, len1, buff2, len2) < 0) {
        *result_length = -1;  // Помечаем ошибку
    } else {
        int borrow = 0;       // Заем из следующего разряда
        int i1 = len1 - 1;    // Индекс в первом числе (идем справа)
        int i2 = len2 - 1;    // Индекс во втором числе (идем справа)
        int pos = 0;          // Позиция в результате
        int temp[LEN];        // Временный массив
        
        // Вычитаем поцифрово справа налево
        while (i1 >= 0) {
            int digit1 = buff1[i1];  // Цифра уменьшаемого
            
            // Цифра вычитаемого (или 0, если цифры закончились)
            int digit2 = (i2 >= 0) ? buff2[i2] : 0;
            
            // Вычитаем с учетом займа
            int diff = digit1 - digit2 - borrow;
            
            // Если результат отрицательный, занимаем 10
            // Например: 3 - 5 = -2
            // Занимаем 10 → 13 - 5 = 8
            if (diff < 0) {
                diff += 10;    // Добавляем занятую десятку
                borrow = 1;    // Запоминаем, что заняли
            } else {
                borrow = 0;    // Ничего не занимали
            }
            
            temp[pos] = diff;  // Записываем цифру результата
            pos++;
            i1--;
            i2--;
        }
        
        // Убираем ведущие нули
        // Например: [0, 0, 7, 8] → [7, 8]
        // Но если все нули, оставляем один:   [0, 0, 0] → [0]
        while (pos > 1 && temp[pos - 1] == 0) {
            pos--;
        }
        
        // Переворачиваем результат (он у нас задом наперед)
        *result_length = pos;
        for (int i = 0; i < pos; i++) {
            result[i] = temp[pos - 1 - i];
        }
    }
}
